def say(message):
    if not speaker:
        return

    speaker.say(message)
    speaker.runAndWait()


def make_idea():
    selected_idea = random.choice(coding_ideas)
    message = "Dealer says: All right, player. Is this your card? Your idea is: " + selected_idea
    print(message)
    say("Ready.")
    time.sleep(0.8)
    say(message)


def wait_for_robot_button(arduino):
    message = arduino.readline().decode(errors="ignore").strip().lower()
    return message == "idea"


def wait_for_keyboard_button():
    if msvcrt:
        key = msvcrt.getch()

        if key in (b"\x00", b"\xe0"):
            key += msvcrt.getch()

        if key.lower() == b"q" or key == b"\x1b":
            return "quit"

        return "idea"

    typed = input("Press Enter for an idea, or q to quit: ").strip().lower()

    if typed == "q":
        return "quit"

    return "idea"


def wait_for_input(mode, arduino):
    if mode == "keyboard":
        return wait_for_keyboard_button()

    if wait_for_robot_button(arduino):
        return "idea"

    return None


def main():
    try:
        import serial
    except ImportError:
        serial = None

    if not speaker:
        print("VOICE IS OFF: The Idea Dealer can print ideas, but cannot talk yet.")
        print("Voice error:", voice_start_error)
        print("Install/fix voice with: pip install pyttsx3")
        print("Also make sure a speaker is connected and your volume is up.")
    else:
        print("Voice is ready.")

    mode = input("Use Arduino button or keyboard? Type arduino or keyboard: ").strip().lower()

    if mode not in ("arduino", "keyboard"):
        mode = "arduino"

    arduino = None

    if mode == "arduino":
        if not serial:
            print("Arduino mode needs pyserial.")
            print("Install it with: pip install pyserial pyttsx3")
            sys.exit(1)

        port = input("Arduino port, like COM3 or COM4: ").strip()
        print("Connecting to Arduino Uno...")

        try:
            arduino = serial.Serial(port, 9600, timeout=1)
        except serial.SerialException as error:
            print("Could not connect to the Arduino.")
            print(error)
            sys.exit(1)

    print("No-screen talking The Idea Dealer is ready.")
    print("Press the robot button or a keyboard key and The Idea Dealer will say an idea out loud.")
    print("Press q or Esc in keyboard mode to quit.")
    print("Press Ctrl+C anytime to quit.")
    say(INTRO_MESSAGE)

    if arduino:
        arduino.reset_input_buffer()

    last_idea_time = 0
    while True:
        action = wait_for_input(mode, arduino)

        if action == "quit":
            break

        if action == "idea":
            now = time.monotonic()

            if now - last_idea_time < COOLDOWN_SECONDS:
                if arduino:
                    arduino.reset_input_buffer()
                continue

            last_idea_time = now
            make_idea()

            if arduino:
                arduino.reset_input_buffer()


if __name__ == "__main__":
    main()
